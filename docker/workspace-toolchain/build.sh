#!/bin/sh
# Builds the workspace toolchain bundle that Petri copies into Kubernetes workspace pods whose image
# lacks the usual command line tools (git, curl, python, go, node/npm ...). Built once, inside the
# Petri image, so that an installation without internet access can still equip a bare pod.
#
# The bundle is a self-contained set of Alpine packages (musl) installed under a FIXED prefix inside
# the pod's workspace volume. Every ELF file is rewritten to use the bundle's own musl loader and
# libraries by absolute path, so the tools run unchanged in glibc images (Debian, Ubuntu, Temurin)
# as well as musl images, and need nothing from the image except /bin/sh.
#
# Runs in an alpine container as root. Environment:
#   PREFIX     installation directory inside the pod         (/petri/workspace/toolchain)
#   PACKAGES   Alpine packages to bundle                     (git curl python3 py3-pip go nodejs npm ...)
#   ARCHES     Alpine architectures to build                 (x86_64 aarch64)
#   OUT        output directory: <OUT>/<amd64|arm64>/toolchain.tar.gz and toolchain.version
set -eu

PREFIX="${PREFIX:-/petri/workspace/toolchain}"
PACKAGES="${PACKAGES:-git curl python3 py3-pip go nodejs npm ca-certificates-bundle}"
ARCHES="${ARCHES:-x86_64 aarch64}"
OUT="${OUT:-/out}"
REPOSITORIES="${REPOSITORIES:-/etc/apk/repositories}"
WORK="${WORK:-/tmp/workspace-toolchain}"
# Downloaded packages are kept here, so that building again (or for the other architecture) is quick.
APK_CACHE="${APK_CACHE:-/var/cache/workspace-toolchain-apk}"
SELF="$(cd "$(dirname "$0")" && pwd)/$(basename "$0")"

apk add --no-cache patchelf tar gzip >/dev/null

# Rewrites "#!/usr/bin/python3" and "#!/usr/bin/env node" to the bundled interpreter by absolute
# path: the bundle must not pick up a different python or node of the image.
rewrite_shebang() {
  file="$1"
  [ -f "$file" ] && [ ! -L "$file" ] || return 0
  [ "$(head -c2 "$file" 2>/dev/null)" = '#!' ] || return 0
  first="$(head -n1 "$file")"
  case "$first" in
    '#!/usr/bin/env '*) rest="${first#'#!/usr/bin/env '}" ;;
    '#!/usr/bin/'*)     rest="${first#'#!/usr/bin/'}" ;;
    *) return 0 ;;
  esac
  name="${rest%% *}"
  args="${rest#"$name"}"
  [ -e "$ROOT/usr/bin/$name" ] || return 0
  # Through the wrapper when there is one, so the interpreter gets the environment it needs (node
  # finds its ICU data, python its certificates) when a script starts it.
  case " $tools " in
    *" $name "*) interpreter="$PREFIX/bin/$name" ;;
    *)           interpreter="$PREFIX/root/usr/bin/$name" ;;
  esac
  sed -i "1s|.*|#!$interpreter$args|" "$file"
}

# Points every ELF file at the bundle's own loader and libraries.
patch_elf() {
  arch="$1"
  loader="$PREFIX/root/lib/ld-musl-$arch.so.1"
  rpath="$PREFIX/root/lib:$PREFIX/root/usr/lib"
  elf="$(printf '\177ELF')"
  find "$ROOT" -type f ! -name 'ld-musl-*' ! -name 'libc.musl-*' | while IFS= read -r file; do
    [ "$(head -c4 "$file" 2>/dev/null)" = "$elf" ] || continue
    if patchelf --print-interpreter "$file" >/dev/null 2>&1; then
      patchelf --set-interpreter "$loader" "$file"
    fi
    # DT_RPATH (not RUNPATH) is searched for the libraries of libraries as well.
    patchelf --force-rpath --set-rpath "$rpath" "$file" 2>/dev/null || true
  done
}

wrapper() {
  name="$1"
  {
    echo '#!/bin/sh'
    echo "# Generated by Petri: runs the bundled $name."
    echo "R=$PREFIX/root"
    echo ': "${SSL_CERT_FILE:=$R/etc/ssl/certs/ca-certificates.crt}"'
    echo 'export SSL_CERT_FILE'
    case "$name" in
      git*)
        # libcurl takes its CA file from this, not from SSL_CERT_FILE.
        echo ': "${GIT_SSL_CAINFO:=$R/etc/ssl/certs/ca-certificates.crt}"'
        echo 'GIT_EXEC_PATH=$R/usr/libexec/git-core'
        echo 'GIT_TEMPLATE_DIR=$R/usr/share/git-core/templates'
        echo 'export GIT_SSL_CAINFO GIT_EXEC_PATH GIT_TEMPLATE_DIR' ;;
      node|node-gyp|npm|npx)
        # Alpine's node looks for its ICU data at an absolute path that is not in the bundle.
        if [ -n "$ICU_DIRECTORY" ]; then
          echo ": \"\${NODE_ICU_DATA:=\$R$ICU_DIRECTORY}\""
          echo 'export NODE_ICU_DATA'
        fi ;;
      go|gofmt)
        echo ': "${GOROOT:=$R/usr/lib/go}"'
        echo ': "${GOTOOLCHAIN:=local}"'
        echo 'export GOROOT GOTOOLCHAIN' ;;
    esac
    echo "exec \"\$R/usr/bin/${2:-$name}\" \"\$@\""
  } > "$STAGE/bin/$name"
  chmod 755 "$STAGE/bin/$name"
}

build() {
  apk_arch="$1"
  case "$apk_arch" in
    x86_64)  go_arch=amd64 ;;
    aarch64) go_arch=arm64 ;;
    *) echo "unsupported architecture $apk_arch" >&2; exit 1 ;;
  esac
  echo "==> workspace toolchain for $apk_arch: $PACKAGES"
  STAGE="$WORK/$apk_arch/stage"
  ROOT="$STAGE/root"
  rm -rf "$WORK/$apk_arch"
  mkdir -p "$ROOT" "$STAGE/bin"

  # The repositories of each architecture are signed with that architecture's keys.
  keys="/usr/share/apk/keys/$apk_arch"
  [ -d "$keys" ] || keys=/etc/apk/keys

  # --no-scripts: the target architecture cannot be executed here, and none is needed.
  # shellcheck disable=SC2086
  apk add --root "$ROOT" --arch "$apk_arch" --initdb --cache-dir "$APK_CACHE" --no-scripts \
    --keys-dir "$keys" --repositories-file "$REPOSITORIES" $PACKAGES >/dev/null

  # What the bundle offers: the commands of the requested packages (not those of their dependencies,
  # which would put things like ldd or getconf in front of the image's own). A command is one of
  # the packages' files in usr/bin, or a link there to one of their files elsewhere (go lives in
  # usr/lib/go/bin and is linked into usr/bin).
  files="$WORK/$apk_arch/package-files"
  : > "$files"
  for package in $PACKAGES; do
    apk info --root "$ROOT" -L "$package" 2>/dev/null >> "$files" || true
  done
  tools=""
  for path in "$ROOT"/usr/bin/*; do
    [ -e "$path" ] || [ -L "$path" ] || continue
    name="${path##*/}"
    owned=""
    if grep -qx "usr/bin/$name" "$files"; then
      owned=yes
    elif [ -L "$path" ]; then
      resolved="$(cd "$ROOT/usr/bin" && readlink -f "$name" 2>/dev/null || true)"
      relative="${resolved#"$ROOT"/}"
      grep -qx "${relative#/}" "$files" && owned=yes
    fi
    [ -n "$owned" ] || continue
    case " $tools " in *" $name "*) ;; *) tools="$tools $name" ;; esac
  done
  [ -n "$tools" ] || { echo "no commands found in: $PACKAGES" >&2; exit 1; }

  ICU_DIRECTORY=""
  icu="$(ls -d "$ROOT"/usr/share/icu/*/ 2>/dev/null | head -1 || true)"
  if [ -n "$icu" ]; then ICU_DIRECTORY="${icu#"$ROOT"}"; ICU_DIRECTORY="${ICU_DIRECTORY%/}"; fi

  version="$( { apk info --root "$ROOT" -v | sort; echo "$PREFIX"; cat "$SELF"; } | sha256sum | cut -c1-16 )"

  for file in "$ROOT"/usr/bin/* "$ROOT"/usr/lib/node_modules/npm/bin/* \
              "$ROOT"/usr/lib/node_modules/npm/node_modules/.bin/*; do
    rewrite_shebang "$file"
  done
  # Links such as usr/bin/go -> /usr/lib/go/bin/go point at the root of the image they were made for.
  find "$ROOT" -type l | while IFS= read -r link; do
    target="$(readlink "$link")"
    case "$target" in
      /*) if [ -e "$ROOT$target" ]; then ln -sfn "$PREFIX/root$target" "$link"; fi ;;
    esac
  done
  patch_elf "$apk_arch"

  for name in $tools; do wrapper "$name"; done
  if [ -e "$ROOT/usr/bin/python3" ] && [ ! -e "$STAGE/bin/python" ]; then wrapper python python3; fi

  # Not needed at run time.
  rm -rf "$ROOT/bin" "$ROOT/sbin" "$ROOT/var" "$ROOT/etc/apk" "$ROOT/lib/apk" "$ROOT/dev" "$ROOT/proc" \
         "$ROOT/usr/share/man" "$ROOT/usr/share/doc" "$ROOT/usr/share/info" "$ROOT/usr/share/apk"

  printf '{"version":"%s","prefix":"%s","arch":"%s"}\n' "$version" "$PREFIX" "$go_arch" \
    > "$STAGE/.petri-toolchain.json"

  mkdir -p "$OUT/$go_arch"
  tar -C "$STAGE" --owner=0 --group=0 --numeric-owner -cf - . | gzip -6 > "$OUT/$go_arch/toolchain.tar.gz"
  echo "$version" > "$OUT/$go_arch/toolchain.version"
  echo "    $(du -h "$OUT/$go_arch/toolchain.tar.gz" | cut -f1) compressed, version $version, commands:$tools"
}

for apk_arch in $ARCHES; do build "$apk_arch"; done
rm -rf "$WORK"
# A development build writes into a directory of the user who started it.
if [ -n "${OWNER:-}" ]; then chown -R "$OWNER" "$OUT"; fi
