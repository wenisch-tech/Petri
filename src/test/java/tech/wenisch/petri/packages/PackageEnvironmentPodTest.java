package tech.wenisch.petri.packages;

import static org.assertj.core.api.Assertions.assertThat;
import static org.mockito.ArgumentMatchers.any;
import static org.mockito.Mockito.mock;
import static org.mockito.Mockito.when;

import java.nio.file.Files;
import java.nio.file.Path;
import java.util.List;
import java.util.UUID;
import org.junit.jupiter.api.AfterEach;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;
import tech.wenisch.petri.kubernetes.RealAgent;
import tech.wenisch.petri.workspace.WorkspaceHost;

/** Package sources reach a command that runs in a Kubernetes pod, checked against the real agent. */
class PackageEnvironmentPodTest {
  @TempDir Path workspace;
  @TempDir Path pki;
  private RealAgent agent;
  private WorkspaceHost host;
  private final UUID projectId = UUID.randomUUID();
  private final PackageRemoteService remotes = mock(PackageRemoteService.class);
  private PackageEnvironment environment;
  private Path podHome;
  private Path cache;

  @BeforeEach
  void setUp() throws Exception {
    agent = RealAgent.start(workspace);
    host = agent.host(projectId);
    environment = new PackageEnvironment(remotes, pki.toString());
    podHome = host.layout().createTemporaryDirectory("petri-term-");
    cache = host.layout().testCaches(projectId);
  }

  @AfterEach
  void tearDown() {
    if (agent != null) agent.close();
  }

  private static PackageToolConfig.Remote remote(
      PackageEcosystem ecosystem, String url, PackageRemoteMode mode, String user, String password) {
    return new PackageToolConfig.Remote(ecosystem, url, mode, user, password, null, false);
  }

  @Test
  void settingsAreRenderedForThePodAndPlacedWhereTheToolsReadThem() throws Exception {
    when(remotes.effective(any())).thenReturn(new PackageRemoteService.Effective(List.of(
        remote(PackageEcosystem.MAVEN, "https://nexus.test/maven", PackageRemoteMode.REPLACE, "ci", "s3cret"),
        remote(PackageEcosystem.NPM, "https://nexus.test/npm", PackageRemoteMode.REPLACE, null, null),
        remote(PackageEcosystem.GRADLE, "https://nexus.test/gradle", PackageRemoteMode.REPLACE, null, null),
        remote(PackageEcosystem.CARGO, "sparse+https://nexus.test/cargo/", PackageRemoteMode.REPLACE, null, null)),
        PackageToolConfig.Trust.NONE));

    var env = environment.remote(projectId, host, podHome, cache);

    // The variables name paths inside the pod, not the temporary directory Petri rendered into.
    assertThat(env.get("MAVEN_ARGS")).contains(podHome + "/pkg/.m2/settings.xml");
    assertThat(env.get("npm_config_userconfig")).isEqualTo(podHome + "/pkg/.npmrc");
    assertThat(env.get("GRADLE_USER_HOME")).isEqualTo(cache + "/gradle");
    assertThat(env.get("CARGO_HOME")).isEqualTo(cache + "/cargo");
    assertThat(env.values()).noneMatch(value -> value.contains("petri-pkg-pod-"));

    assertThat(Files.readString(podHome.resolve("pkg/.m2/settings.xml")))
        .contains("https://nexus.test/maven").contains("s3cret");
    assertThat(java.nio.file.attribute.PosixFilePermissions.toString(
        Files.getPosixFilePermissions(podHome.resolve("pkg/.m2/settings.xml"))))
        .as("a file with credentials stays private in the pod").isEqualTo("rw-------");
    assertThat(Files.readString(podHome.resolve("pkg/.npmrc"))).contains("registry=https://nexus.test/npm");
    assertThat(Files.readString(cache.resolve("gradle/init.d/petri-remotes.gradle"))).contains("nexus.test/gradle");
    assertThat(Files.readString(cache.resolve("cargo/config.toml"))).contains("nexus.test/cargo");
  }

  @Test
  void aFileLeftByARemoteThatNoLongerExistsIsRemovedButAUsersOwnIsKept() throws Exception {
    Path stale = Files.createDirectories(cache.resolve("composer")).resolve("config.json");
    Files.writeString(stale, "{\"//\": \"Generated by Petri\"}");
    Path own = Files.createDirectories(cache.resolve("cargo")).resolve("config.toml");
    Files.writeString(own, "[net]\nretry = 5\n");
    when(remotes.effective(any())).thenReturn(new PackageRemoteService.Effective(List.of(
        remote(PackageEcosystem.NPM, "https://nexus.test/npm", PackageRemoteMode.REPLACE, null, null)),
        PackageToolConfig.Trust.NONE));

    environment.remote(projectId, host, podHome, cache);

    assertThat(stale).doesNotExist();
    assertThat(own).exists();
  }

  @Test
  void theCertificateBundleTravelsWithTheConfiguration() throws Exception {
    Path pem = Files.writeString(pki.resolve("ca-1.pem"), "-----BEGIN CERTIFICATE-----\nAAAA\n-----END CERTIFICATE-----\n");
    Path store = Files.writeString(pki.resolve("ca-1.p12"), "pkcs12");
    when(remotes.effective(any())).thenReturn(new PackageRemoteService.Effective(List.of(
        remote(PackageEcosystem.MAVEN, "https://nexus.test/maven", PackageRemoteMode.REPLACE, null, null)),
        new PackageToolConfig.Trust(pem, store, "changeit", false)));

    var env = environment.remote(projectId, host, podHome, cache);

    assertThat(env.get("SSL_CERT_FILE")).isEqualTo(podHome + "/pkg/pki/ca-1.pem");
    assertThat(env.get("MAVEN_ARGS")).contains("-Djavax.net.ssl.trustStore=" + podHome + "/pkg/pki/ca-1.p12");
    assertThat(Files.readString(podHome.resolve("pkg/pki/ca-1.pem"))).contains("BEGIN CERTIFICATE");
    assertThat(podHome.resolve("pkg/pki/ca-1.p12")).exists();
  }

  @Test
  void withoutConfiguredSourcesNothingIsAddedOrCopied() throws Exception {
    when(remotes.effective(any())).thenReturn(
        new PackageRemoteService.Effective(List.of(), PackageToolConfig.Trust.NONE));
    assertThat(environment.remote(projectId, host, podHome, cache)).isEmpty();
    assertThat(podHome.resolve("pkg")).doesNotExist();
  }
}
