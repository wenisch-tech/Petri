package tech.wenisch.petri.packages;

import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.StandardCopyOption;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.UUID;
import org.springframework.beans.factory.annotation.Value;
import org.springframework.stereotype.Component;
import tech.wenisch.petri.workspace.WorkspaceHost;

/**
 * What the configured package remotes add to a command's environment, for the instance or for a
 * project. Used by every place that starts a process which fetches packages.
 */
@Component
public class PackageEnvironment {
  private static final String CONTAINER_FILES = "/petri-pkg";
  private static final String CONTAINER_PKI = "/petri-pki";
  /** Tool configuration that has no environment variable: copied into the tool's own home. */
  private static final Map<String, String[]> PLACED = Map.of(
      "GRADLE_USER_HOME", new String[] {PackageToolConfig.FILES_DIRECTORY + "/gradle-remotes.gradle",
          "init.d/petri-remotes.gradle"},
      "CARGO_HOME", new String[] {PackageToolConfig.FILES_DIRECTORY + "/cargo-config.toml",
          "config.toml"},
      "COMPOSER_HOME", new String[] {PackageToolConfig.FILES_DIRECTORY + "/composer-config.json",
          "config.json"});

  private final PackageRemoteService remotes;
  private final Path pkiDirectory;

  PackageEnvironment(
      PackageRemoteService remotes,
      @Value("${petri.packages.pki-dir:./data/pki}") String pkiDirectory) {
    this.remotes = remotes;
    this.pkiDirectory = Path.of(pkiDirectory).toAbsolutePath().normalize();
  }

  /** Writes tool config under {@code home} and returns the variables that point at it. */
  public Map<String, String> environment(UUID projectId, Path home) {
    PackageRemoteService.Effective effective = remotes.effective(projectId);
    if (effective.empty()) return Map.of();
    try {
      presentGoCertificates(effective, home);
      return PackageToolConfig.render(effective.remotes(), effective.trust(), home).env();
    } catch (IOException exception) {
      throw new IllegalStateException(
          "Could not prepare the package remote settings: " + exception.getMessage(), exception);
    }
  }

  /**
   * Go has no way to skip certificate verification for its proxy, so for an insecure Go remote the
   * certificates the server presents are written to {@code home} to be trusted explicitly.
   */
  private static void presentGoCertificates(PackageRemoteService.Effective effective, Path home)
      throws IOException {
    Path file = home.resolve(PackageToolConfig.PRESENTED_CERTIFICATES);
    Files.deleteIfExists(file);
    StringBuilder pem = new StringBuilder();
    for (var remote : effective.remotes()) {
      if (remote.ecosystem() != PackageEcosystem.GO
          || !(remote.insecure() || effective.trust().ignoreTlsErrors())) continue;
      try {
        String chain = PackageServerCertificates.fetch(remote.url());
        if (chain != null) pem.append(chain);
      } catch (IOException exception) {
        // unreachable now: Go will report the connection error itself
      }
    }
    if (!pem.isEmpty()) Files.writeString(file, pem.toString());
  }

  /**
   * Copies generated files that tools only find in their own home (Gradle's init script, Cargo's
   * and Composer's config) into the homes named by the command environment, and removes ones left
   * by remotes that no longer exist.
   */
  public void placeToolFiles(Path home, Map<String, String> commandEnvironment) {
    placeToolFiles(home, commandEnvironment, true);
  }

  private void placeToolFiles(Path home, Map<String, String> homes, boolean fromEnvironment) {
    for (var entry : PLACED.entrySet()) {
      String directory = homes.get(entry.getKey());
      if (directory == null || directory.isBlank()) continue;
      Path source = home.resolve(entry.getValue()[0]);
      Path target = Path.of(directory).resolve(entry.getValue()[1]);
      try {
        if (Files.isRegularFile(source)) {
          Files.createDirectories(target.getParent());
          Files.copy(source, target, StandardCopyOption.REPLACE_EXISTING);
        } else if (Files.isRegularFile(target) && isGenerated(target)) {
          Files.delete(target);
        }
      } catch (IOException exception) {
        throw new IllegalStateException(
            "Could not place the package remote settings: " + exception.getMessage(), exception);
      }
    }
  }

  private static boolean isGenerated(Path file) throws IOException {
    try (var lines = Files.lines(file)) {
      return lines.limit(1).anyMatch(line -> line.contains("Generated by Petri"));
    }
  }

  /**
   * @param containerEnv variables for inside the container ({@code --env})
   * @param hostEnv variables for the Podman process itself (registries.conf, credentials, CA)
   * @param volumes {@code --volume} arguments to add
   */
  public record Container(
      Map<String, String> containerEnv, Map<String, String> hostEnv, List<String> volumes) {
    public static final Container NONE = new Container(Map.of(), Map.of(), List.of());
  }

  /**
   * Package configuration for a Podman run: files are written to {@code home} (mounted read-only
   * at /petri-pkg), tools inside are pointed at them, and Podman itself gets the registry mirror
   * configuration for pulling the image.
   */
  public Container container(UUID projectId, Path home, Path cache) {
    PackageRemoteService.Effective effective = remotes.effective(projectId);
    if (effective.empty()) return Container.NONE;
    try {
      PackageToolConfig.Trust inside = effective.trust().pemBundle() == null
          ? effective.trust() : effective.trust().relocated(CONTAINER_PKI);
      presentGoCertificates(effective, home);
      var rendered = PackageToolConfig.render(effective.remotes(), inside, home, CONTAINER_FILES);
      Map<String, String> containerEnv = new LinkedHashMap<>(rendered.env());
      Map<String, String> hostEnv = new LinkedHashMap<>();
      for (String name : List.of("CONTAINERS_REGISTRIES_CONF", "REGISTRY_AUTH_FILE")) {
        String value = containerEnv.remove(name);
        if (value != null) hostEnv.put(name, home.resolve(value.substring(CONTAINER_FILES.length() + 1)).toString());
      }
      if (effective.trust().pemBundle() != null) {
        hostEnv.put("SSL_CERT_FILE", effective.trust().pemBundle().toString());
      }
      // Tools that read their configuration from their own home: cache subdirectories.
      Map<String, String> homes = new LinkedHashMap<>();
      homes.put("GRADLE_USER_HOME", cache.resolve("gradle").toString());
      homes.put("CARGO_HOME", cache.resolve("cargo").toString());
      homes.put("COMPOSER_HOME", cache.resolve("composer").toString());
      placeToolFiles(home, homes, false);
      for (var entry : PLACED.entrySet()) {
        if (Files.isRegularFile(home.resolve(entry.getValue()[0]))) {
          containerEnv.put(entry.getKey(), "/cache/" + switch (entry.getKey()) {
            case "GRADLE_USER_HOME" -> "gradle";
            case "CARGO_HOME" -> "cargo";
            default -> "composer";
          });
        }
      }
      List<String> volumes = new ArrayList<>();
      volumes.addAll(List.of("--volume", home + ":" + CONTAINER_FILES + ":ro,Z"));
      if (effective.trust().pemBundle() != null && Files.isDirectory(pkiDirectory)) {
        volumes.addAll(List.of("--volume", pkiDirectory + ":" + CONTAINER_PKI + ":ro,z"));
      }
      return new Container(Map.copyOf(containerEnv), Map.copyOf(hostEnv), List.copyOf(volumes));
    } catch (IOException exception) {
      throw new IllegalStateException(
          "Could not prepare the package remote settings: " + exception.getMessage(), exception);
    }
  }

  /**
   * Package settings for a command that runs in a Kubernetes pod. The tool configuration is rendered
   * here, with paths as they will be inside the pod, copied into {@code podHome/pkg} (which must lie
   * in the pod's scratch space) and, for tools that only read their own home, placed into the
   * project's build cache there. Returns the variables that point the tools at the files.
   *
   * <p>The files hold repository credentials, so they live only as long as {@code podHome}; the
   * caller removes that directory when the command ends.
   */
  public Map<String, String> remote(UUID projectId, WorkspaceHost host, Path podHome, Path podCache)
      throws IOException {
    PackageRemoteService.Effective effective = remotes.effective(projectId);
    if (effective.empty()) return Map.of();
    String podFiles = unix(podHome) + "/pkg";
    Path staging = Files.createTempDirectory("petri-pkg-pod-");
    try {
      PackageToolConfig.Trust trust = effective.trust();
      if (trust.pemBundle() != null) {
        // The certificate files travel with the configuration instead of being mounted.
        Path pki = Files.createDirectories(staging.resolve("pki"));
        Files.copy(trust.pemBundle(), pki.resolve(trust.pemBundle().getFileName().toString()));
        if (trust.truststore() != null) {
          Files.copy(trust.truststore(), pki.resolve(trust.truststore().getFileName().toString()));
        }
        trust = trust.relocated(podFiles + "/pki");
      }
      presentGoCertificates(effective, staging);
      PackageToolConfig.Rendered rendered =
          PackageToolConfig.render(effective.remotes(), trust, staging, podFiles);
      Map<String, String> env = new LinkedHashMap<>(rendered.env());
      // Registry configuration for Podman pulling an image: irrelevant inside a pod.
      env.remove("CONTAINERS_REGISTRIES_CONF");
      env.remove("REGISTRY_AUTH_FILE");

      Map<String, String> homes = Map.of(
          "GRADLE_USER_HOME", unix(podCache) + "/gradle",
          "CARGO_HOME", unix(podCache) + "/cargo",
          "COMPOSER_HOME", unix(podCache) + "/composer");
      StringBuilder place = new StringBuilder("set -e\n");
      for (var entry : PLACED.entrySet()) {
        String home = homes.get(entry.getKey());
        String source = podFiles + "/" + entry.getValue()[0];
        String target = home + "/" + entry.getValue()[1];
        if (Files.isRegularFile(staging.resolve(entry.getValue()[0]))) {
          place.append("mkdir -p ").append(quote(parent(target))).append(" && cp ")
              .append(quote(source)).append(' ').append(quote(target)).append('\n');
          env.put(entry.getKey(), home);
        } else {
          // A file left by remotes that no longer exist; only Petri's own are removed.
          place.append("if [ -f ").append(quote(target)).append(" ] && grep -q 'Generated by Petri' ")
              .append(quote(target)).append("; then rm -f ").append(quote(target)).append("; fi\n");
        }
      }
      host.archives().uploadTree(staging, Path.of(podFiles));
      var result = host.processes().exec(podHome, List.of("sh", "-c", place.toString()), Map.of(),
          java.time.Duration.ofSeconds(60), 8192, null, null);
      if (result.exitCode() != 0) {
        throw new IllegalStateException("Could not place the package remote settings in the pod: "
            + result.output().strip());
      }
      return env;
    } finally {
      try (var walk = Files.walk(staging)) {
        walk.sorted(java.util.Comparator.reverseOrder()).forEach(path -> path.toFile().delete());
      } catch (IOException ignored) {
        // only generated configuration
      }
    }
  }

  private static String unix(Path path) {
    return path.toString().replace('\\', '/');
  }

  private static String parent(String path) {
    int slash = path.lastIndexOf('/');
    return slash <= 0 ? "/" : path.substring(0, slash);
  }

  private static String quote(String value) {
    return "'" + value.replace("'", "'\\''") + "'";
  }

  /** Whether apk must not verify HTTPS certificates (an insecure apk remote, or the global switch). */
  public boolean apkInsecure(UUID projectId) {
    PackageRemoteService.Effective effective = remotes.effective(projectId);
    return effective.trust().ignoreTlsErrors() || effective.remotes().stream().anyMatch(
        value -> value.ecosystem() == PackageEcosystem.APK && value.insecure());
  }

  /** Repository lines for apk, or null when the image's own repositories apply. */
  public List<String> apkRepositories(UUID projectId) {
    return PackageToolConfig.apk(remotes.effective(projectId).remotes());
  }
}
